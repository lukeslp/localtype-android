    @Test
    fun `a finished field chain hashes the same in every later export of the file`() {
        val lines = generated.lines
        val full = log.chains.map { it.fingerprint }
        // An earlier export ends at a chain's last EF; the snapshots and chains appended after it don't move what it holds.
        for (chain in log.chains) {
            val end = lines.indexOfFirst { (PredictionLogCodec.decode(it) as? LogRecord.FieldEnd)?.seq == chain.seqs.last() }
            val earlier = PredictionLogCorpus.load(lines.subList(0, end + 1)).chains.map { it.fingerprint }
            assertEquals("chains in an export that ends with chain ${chain.number}", full.take(chain.number), earlier)
        }
        // A process restart appends a table block: after the last EF, or after a field that died with no EF.
        val snap = lines.indexOfFirst { it.startsWith("SNAP\t") }
        val table = lines.subList(snap, lines.indexOf("END") + 1)
        assertEquals("a snapshot after the last EF", full, PredictionLogCorpus.load(lines + table).chains.map { it.fingerprint })
        val lastEnd = lines.indexOfLast { it.startsWith("EF\t") }
        assertEquals(
            "a snapshot after a field with no EF",
            PredictionLogCorpus.load(lines.subList(0, lastEnd)).chains.last().fingerprint,
            PredictionLogCorpus.load(lines.subList(0, lastEnd) + table).chains.last().fingerprint,
        )
    }

