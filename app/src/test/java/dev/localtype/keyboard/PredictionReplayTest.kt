    @Test
    fun `many field chains with a steady lead pass and a regression in completion does not`() {
        // Forty copies of the two-chain log's first chain, each its own chain: the strip leads by a point of margin every time.
        val dict = TypoCorpus.dictionary.size
        fun file(completionRegresses: Boolean): ParsedLog {
            val records = ArrayList<LogRecord>()
            records += LogRecord.Snapshot(PredictionLogCodec.SNAP_FILE, 0)
            records += LogRecord.SnapshotEnd
            for (n in 1..40) {
                records += LogRecord.Field(n, false, true, false, 0, true, NeuralAsset.SHA256)
                records += LogRecord.Word(n, n, "", false, true, "", false)
                records += LogRecord.Offer(n, 0, "", 'L', 'N', true, listOf("the" to 3, "to" to 2, "a" to 1), listOf("Thanks", "The", "To"), "NRR", 0, dict, 10, 20)
                // With the regression the strip loses the word again at one letter while the plain ranking has it.
                records += LogRecord.Offer(n, 1, "t", 'L', 'N', true, listOf("the" to 3, "to" to 2, "thanks" to 1),
                    if (completionRegresses) listOf("the", "to", "too") else listOf("thanks", "the", "to"), if (completionRegresses) "RRR" else "NRR", 0, dict, 10, 20)
                records += LogRecord.Typed(n, "thanks", "thanks", ' ', false, true, true)
                records += LogRecord.FieldEnd(n, 0, 0, 0, 0, 0, 0, 0, 0)
            }
            val header = PredictionLogCodec.neuralHeader(NeuralAsset.SHA256) + mapOf("code" to "38", "app" to "0.5.18")
            return PredictionLogCorpus.load((PredictionLogCodec.encodeHeader(header) + PredictionLogCodec.encodeBlock(records)).trimEnd('\n').split('\n'))
        }
        val steady = slots(file(completionRegresses = false))
        val d = steady.displayedSlots(DisplayedSlots.Mode.AS_LOGGED)
        assertEquals(40, d.chains)
        assertEquals(1.0 / 7, d.savings.difference, 1e-12)
        assertTrue(d.savings.low > 0.0)
        assertTrue(steady.displayedSlotsVerdict, steady.displayedSlotsVerdict.startsWith("PASSED"))
        val regressed = slots(file(completionRegresses = true))
        assertTrue(regressed.displayedSlots(DisplayedSlots.Mode.AS_LOGGED).completion.high < 0.0)
        assertTrue(regressed.displayedSlotsVerdict, regressed.displayedSlotsVerdict.startsWith("NOT PASSED: the completion hit rate regressed"))
    }

    @Test
    fun `without a completion observation no gate is read, and one losing observation is a regression`() {
        // Forty chains of a six-letter word tapped before any letter from a neural slot the plain list never had.
        val dict = TypoCorpus.dictionary.size
        fun file(losingCompletion: Boolean): ParsedLog {
            val records = ArrayList<LogRecord>()
            records += LogRecord.Snapshot(PredictionLogCodec.SNAP_FILE, 0)
            records += LogRecord.SnapshotEnd
            for (n in 1..40) {
                records += LogRecord.Field(n, false, true, false, 0, true, NeuralAsset.SHA256)
                records += LogRecord.Word(n, n, "", false, true, "", false)
                records += LogRecord.Offer(n, 0, "", 'L', 'N', true, listOf("the" to 3, "to" to 2, "a" to 1), listOf("Thanks", "The", "To"), "NRR", 0, dict, 10, 20)
                if (losingCompletion && n == 1) {
                    // One chain types the word through, and at one letter only the plain list has it.
                    records += LogRecord.Offer(n, 1, "t", 'L', 'N', true, listOf("thanks" to 3, "to" to 2, "the" to 1), listOf("the", "to", "too"), "RRR", 0, dict, 10, 20)
                    records += LogRecord.Typed(n, "thanks", "thanks", ' ', false, true, true)
                } else records += LogRecord.Tap(n, 0, 0, "Thanks", 'N', true)
                records += LogRecord.FieldEnd(n, 0, 0, 0, 0, 0, 0, 0, 0)
            }
            val header = PredictionLogCodec.neuralHeader(NeuralAsset.SHA256) + mapOf("code" to "38", "app" to "0.5.18")
            return PredictionLogCorpus.load((PredictionLogCodec.encodeHeader(header) + PredictionLogCodec.encodeBlock(records)).trimEnd('\n').split('\n'))
        }
        val none = slots(file(losingCompletion = false))
        assertEquals(0, none.displayedSlots(DisplayedSlots.Mode.AS_LOGGED).completionPairs)
        assertTrue(none.displayedSlots(DisplayedSlots.Mode.AS_LOGGED).clearsMargin)
        assertTrue(none.displayedSlots(DisplayedSlots.Mode.TAP_BOUND).clearsMargin)
        assertTrue(none.displayedSlotsVerdict, none.displayedSlotsVerdict.startsWith("not read: no offer at one letter or more"))
        assertTrue(none.report(none.run("device")).contains("gate: not read: no offer at one letter or more"))
        val one = slots(file(losingCompletion = true))
        val d = one.displayedSlots(DisplayedSlots.Mode.AS_LOGGED)
        assertEquals(1, d.completionPairs)
        assertEquals(1, d.completion.lines)
        assertEquals(-1.0, d.completion.high, 0.0)
        assertTrue(one.displayedSlotsVerdict, one.displayedSlotsVerdict.startsWith("NOT PASSED: the completion hit rate regressed"))
    }

