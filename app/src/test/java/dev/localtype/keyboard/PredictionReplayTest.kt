/**
 * The replay harness on the scripted fixture: structure and hand-computable arithmetic only, so a
 * ranker change never fails the gate. Every count comes from what the script did, and every failure
 * names the count. A real exported log is replayed only when `-Dlocaltype.log` or `LOCALTYPE_LOG` is set.
 */
class PredictionReplayTest {
    private companion object {
        // Generated once for the class: the fixture and its scoring share TypoCorpus.dictionary, so O.dict matches the harness.
        val generated: PredictionLogFixture.Generated by lazy { PredictionLogFixture.generateWithExpectations() }
        val log: ParsedLog by lazy { PredictionLogCorpus.load(generated.lines) }
        val evaluation: Evaluation by lazy {
            fixtureScorer().evaluate(log, listOf(DeviceRanker(), BigramReplayRanker(), TrigramReplayRanker()), PredictionLogCorpus.Parity.ALL)
        }

        /** The fixture's device has its own short seeds, which the prior's fade needs to tell from the person's pairs. */
        fun fixtureScorer() = Scorer(seedPhrases = PredictionLogFixture.SEEDS, sentenceStarters = PredictionLogFixture.STARTERS)

        /** The fixture's lines with its `#key=` header line replaced by [replacement], or dropped when that's null. */
        fun withHeader(key: String, replacement: String?): List<String> =
            generated.lines.mapNotNull { line -> if (line.startsWith("#$key=")) replacement?.let { "#$key=$it" } else line }
    }

    private val expected get() = generated.expected
    private val device get() = evaluation.run("device")
    private val bigram get() = evaluation.run("bigram-replay")
    private val trigram get() = evaluation.run("trigram-replay")

    private fun neuralLog(digest: String = NeuralAsset.SHA256, fieldDigest: String? = digest, headerDigest: String? = digest, src: Char = 'N'): ParsedLog {
        val records = listOf(
            LogRecord.Snapshot(PredictionLogCodec.SNAP_FILE, 0), LogRecord.SnapshotEnd,
            LogRecord.Field(1, false, true, false, 0, true, fieldDigest),
            // A cut, redacted sentence deliberately cannot reproduce the model's input.
            LogRecord.Word(1, 1, "0 ", true, false, "", false),
            LogRecord.Offer(1, 0, "", 'L', 'N', true, listOf("the" to 100), listOf("thanks", "the", "hello"), "${src}RR", 0, TypoCorpus.dictionary.size, 10, 20),
            LogRecord.Tap(1, 0, 0, "thanks", src, true),
            LogRecord.FieldEnd(1, 0, 0, 0, 0, 0, 0, 0, 0),
        )
        val header = PredictionLogCodec.encodeHeader(PredictionLogCodec.neuralHeader(headerDigest))
        return PredictionLogCorpus.load((header + PredictionLogCodec.encodeBlock(records)).trimEnd('\n').split('\n'))
    }

    @Test
    fun `neural and protected personal strip successes are separate from ngram reference success`() {
        for (src in listOf('N', 'P')) {
            val neural = neuralLog(src = src)
            val result = fixtureScorer().evaluate(neural, listOf(DeviceRanker(), BigramReplayRanker()), PredictionLogCorpus.Parity.ALL)
            assertEquals(NeuralAsset.SHA256, result.build!!.neuralSha256)
            val d = result.device()
            assertEquals(0, d.realizedSaved)
            assertEquals(0, d.rankerTaps)
            assertEquals(if (src == 'N') 6 else 0, d.neuralSaved)
            assertEquals(if (src == 'N') 1 else 0, d.neuralTaps)
            assertEquals(if (src == 'P') 6 else 0, d.personalSaved)
            assertEquals(if (src == 'P') 1 else 0, d.personalTaps)
            assertEquals(1.0, d.tapRate, 0.0)
            assertEquals(1.0, d.stripHit3, 0.0)
            val raw = result.metrics(result.run("device"), Evaluation.Ladder.LOGGED)
            assertEquals(0, raw.potentialSaved)
            val report = result.report(result.run("device"))
            assertTrue(report.contains("${if (src == 'N') "neural" else "personal"}_saved 6 (never added)"))
            assertTrue(report.contains("No neural agreement or full-ladder neural comparison is claimed"))
            assertTrue(report.contains("O.ranked and replay agreement describe the n-gram reference only"))
        }
    }

    /**
     * Three words in two field chains with Chime on. "thanks": the strip has it before any letter, the plain
     * ranking at one letter. "hello": an emoji holds a slot before any letter, so the plain ranking gets two
     * words there and still has it; the strip shows it at one letter. "morning": tapped at one letter from a
     * neural slot the plain ranking never matched.
     */
    private fun slotsLog(code: String? = "38", neural: String? = NeuralAsset.SHA256, tapSrc: Char = 'N'): ParsedLog {
        val dict = TypoCorpus.dictionary.size
        fun offer(wid: Int, p: Int, prefix: String, ranked: List<String>, slots: List<String>, src3: String) =
            LogRecord.Offer(wid, p, prefix, 'L', 'N', true, ranked.mapIndexed { n, w -> w to 100 - n }, slots, src3, 0, dict, 10, 20)
        val records = listOf(
            LogRecord.Snapshot(PredictionLogCodec.SNAP_FILE, 0), LogRecord.SnapshotEnd,
            LogRecord.Field(1, false, true, false, 0, true, neural),
            LogRecord.Word(1, 1, "", false, true, "", false),
            offer(1, 0, "", listOf("the", "to", "a"), listOf("Thanks", "The", "To"), "NRR"),
            offer(1, 1, "t", listOf("the", "to", "thanks"), listOf("thanks", "the", "to"), "NRR"),
            LogRecord.Typed(1, "thanks", "thanks", ' ', false, true, true),
            LogRecord.Word(2, 1, "thanks ", false, false, "thanks", false),
            offer(2, 0, "", listOf("hello", "hi", "hey"), listOf("hi", "hey", "🙂"), "RRE"),
            offer(2, 1, "h", listOf("hi", "hey", "hello"), listOf("hello", "hi", "hey"), "RRR"),
            LogRecord.Typed(2, "hello", "hello", ' ', false, true, true),
            LogRecord.FieldEnd(1, 0, 0, 0, 0, 0, 0, 0, 0),
            LogRecord.Field(2, false, true, false, 0, true, neural),
            LogRecord.Word(3, 2, "", false, true, "", false),
            offer(3, 0, "", listOf("the", "to", "a"), listOf("The", "To", "A"), "RRR"),
            offer(3, 1, "m", listOf("my", "me", "more"), listOf("morning", "my", "me"), "${tapSrc}RR"),
            LogRecord.Tap(3, 1, 0, "morning", tapSrc, true),
            LogRecord.FieldEnd(2, 0, 0, 0, 0, 0, 0, 0, 0),
        )
        val header = PredictionLogCodec.neuralHeader(neural) + (code?.let { mapOf("code" to it, "app" to "0.5.18") } ?: emptyMap())
        return PredictionLogCorpus.load((PredictionLogCodec.encodeHeader(header) + PredictionLogCodec.encodeBlock(records)).trimEnd('\n').split('\n'))
    }

    private fun slots(log: ParsedLog) = fixtureScorer().evaluate(log, listOf(DeviceRanker()), PredictionLogCorpus.Parity.ALL)

