    /** The trigram control with the evidence behind every answer recorded, so a test can tell which rungs had a context to use. */
    private class ProbedTrigram : Ranker {
        private val inner = TrigramReplayRanker("trigram-probe")
        override val name get() = inner.name
        override val adaptive get() = inner.adaptive

        /** The most trigram evidence any predict on this (sentence, prefix) had; zero means the term was zero every time. */
        val evidence = HashMap<Pair<String, String>, Int>()

        override fun reset(tables: AdaptiveNgramModel.Tables, dictionary: WordDictionary, build: ReplayBuild) = inner.reset(tables, dictionary, build)
        override fun dictionary(dictionary: WordDictionary) = inner.dictionary(dictionary)

        override fun predict(sentence: String, prefix: String, limit: Int): List<Pair<String, Int>> {
            val key = sentence to prefix
            evidence[key] = maxOf(evidence[key] ?: 0, inner.evidence(sentence, prefix))
            return inner.predict(sentence, prefix, limit)
        }

        override fun observe(previous: String?, word: String) = inner.observe(previous, word)
        override fun observeWord(word: String) = inner.observeWord(word)
    }

    /** Always the same six words: the frozen column of a candidate that cannot learn. */
    private class StubRanker(override val name: String = "stub-fixed", override val trainedOn: Set<String> = emptySet()) : Ranker {
        override val adaptive = false
        private val fixed = listOf("the", "to", "and", "a", "i", "you")
        override fun reset(tables: AdaptiveNgramModel.Tables, dictionary: WordDictionary, build: ReplayBuild) = Unit
        override fun predict(sentence: String, prefix: String, limit: Int): List<Pair<String, Int>> {
            val normalized = AdaptiveNgramModel.normalize(prefix)
            return fixed.filter { it.startsWith(normalized) }.take(limit).mapIndexed { n, word -> word to (fixed.size - n) }
        }
        override fun observe(previous: String?, word: String) = Unit
        override fun observeWord(word: String) = Unit
    }
