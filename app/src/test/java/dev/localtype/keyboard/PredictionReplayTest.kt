    @Test
    fun `replay applies each learned mutation at its record and never changes prediction targets`() {
        val delegate = BigramReplayRanker()
        val observed = mutableListOf<Pair<String?, String>>()
        val probe = object : Ranker by delegate {
            override val name = "repair-learning-probe"
            override fun observe(previous: String?, word: String) {
                observed += previous to word
                delegate.observe(previous, word)
            }
            override fun observeWord(word: String) {
                observed += "hidden-prev" to word
                delegate.observeWord(word)
            }
        }
        fixtureScorer().evaluate(log, listOf(DeviceRanker(), BigramReplayRanker(), probe), PredictionLogCorpus.Parity.ALL)
        val chronological = log.entries.mapNotNull { entry -> when (entry) {
            is ParsedLog.Entry.Word -> entry.instance.takeIf { it.mutates }?.let { i ->
                val previous = i.observedPrevious
                (if (previous == null) "hidden-prev" else previous.ifEmpty { null }) to i.target
            }
            is ParsedLog.Entry.Repair -> entry.record.takeIf { it.learned }?.let { r ->
                (when (r.prev) { "" -> "hidden-prev"; AdaptiveNgramModel.START -> null; else -> r.prev }) to r.replacement
            }
            is ParsedLog.Entry.Mutation -> entry.record.takeIf { it.word.isNotEmpty() }?.let { r ->
                (when (r.prev) { "" -> "hidden-prev"; AdaptiveNgramModel.START -> null; else -> r.prev }) to r.word
            }
            else -> null
        } }
        assertEquals(chronological, observed)
        assertEquals(log.instances.count { it.mutates } + log.mutations.count { it.word.isNotEmpty() } + 1, observed.size)
        assertFalse(observed.any { it.second == "tehh" })
        assertEquals(1, log.instances.count { it.target == "tehh" })
        assertEquals(0, Metrics.compute(listOf(log.instances.single { it.target == "tehh" })) { it.loggedLadder }.potentialSaved)
    }

    @Test
    fun `Undo of an immediate correction excludes benefit but never reverts learned model effects`() {
        val immediate = log.repairs.first { it.record.outcome == 'P' && !it.record.learned }
        val following = log.instances.first { it.ordinal > immediate.instance.ordinal && it.typed != null }
        val after = PredictionLogCodec.encode(following.outcome)
        val undo = immediate.record.copy(outcome = 'U', learned = false)
        val lines = generated.lines.flatMap { if (it == after) listOf(it, PredictionLogCodec.encode(undo)) else listOf(it) }
        val modified = PredictionLogCorpus.load(lines)
        assertEquals(0, modified.stray)
        assertEquals(1, modified.repairBenefit)
        assertEquals(1, modified.repairLearning)
        val result = fixtureScorer().evaluate(modified, listOf(DeviceRanker(), BigramReplayRanker()), PredictionLogCorpus.Parity.ALL)
        assertEquals(evaluation.device().autocorrected - 1, result.device().autocorrected)
        assertEquals(evaluation.device().realizedSaved, result.device().realizedSaved)
        assertEquals(log.instances.map { it.target }, modified.instances.map { it.target })
        assertEquals(1.0, result.run("bigram-replay").agreement!!.top3Rate, 0.0)
    }

    @Test
    fun `corrupted repair records invalidate learning and benefit safely`() {
        val learned = log.repairs.single { it.record.learned }
        val encoded = PredictionLogCodec.encode(learned.record)
        val invalids = listOf(encoded.replace("FIX\t${learned.record.wid}", "FIX\t99999"),
            encoded.replace("\tP\t1\t", "\tU\t1\t"), encoded + "\ttorn")
        for (invalid in invalids) {
            val damaged = PredictionLogCorpus.load(generated.lines.map { if (it == encoded) invalid else it })
            assertEquals(0, damaged.repairLearning)
            assertEquals(2, damaged.repairBenefit)
            assertTrue(damaged.hiddenMutations > log.hiddenMutations)
            assertTrue(damaged.instances.last().shadow)
            assertTrue(damaged.stats.malformed > 0 || damaged.stray > 0)
            val result = fixtureScorer().evaluate(damaged, listOf(DeviceRanker(), BigramReplayRanker()), PredictionLogCorpus.Parity.ALL)
            assertEquals(1.0, result.run("bigram-replay").agreement!!.top3Rate, 0.0)
        }
        val undo = PredictionLogCodec.encode(log.repairs.single { it.record.outcome == 'U' }.record)
        val missingUndo = PredictionLogCorpus.load(generated.lines.map { if (it == undo) it + "\ttorn" else it })
        assertEquals(2, missingUndo.repairBenefit)
        assertEquals(1, missingUndo.repairLearning)
    }

